// Generates src/api/schema.gen.ts from the pinned contract, src/api/openapi.yaml
// (docs/architecture/conventions.md, "API client"). Run with `make generate`.
//
// Two mappings on top of openapi-typescript's defaults:
// - `format: decimal` (Money.amount) becomes `Decimal`, exact decimal text,
//   never a JS number (ADR-0002);
// - `x-extensible-enum` becomes its known values plus any other string, so a
//   switch gets autocompletion and an unknown value still type-checks.
import { writeFile } from "node:fs/promises";

import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const source = new URL("../src/api/openapi.yaml", import.meta.url);
const target = new URL("../src/api/schema.gen.ts", import.meta.url);

const { factory } = ts;
const decimal = factory.createTypeReferenceNode("Decimal");
// `string & {}` keeps the literals from collapsing into plain `string`.
const anyOtherString = factory.createIntersectionTypeNode([
  factory.createKeywordTypeNode(ts.SyntaxKind.StringKeyword),
  factory.createTypeLiteralNode([]),
]);

function isStringArray(value: unknown): value is string[] {
  return Array.isArray(value) && value.every((item) => typeof item === "string");
}

const ast = await openapiTS(source, {
  transform(schema) {
    if (schema.format === "decimal") {
      return decimal;
    }
    const known: unknown = (schema as Record<string, unknown>)["x-extensible-enum"];
    if (isStringArray(known)) {
      return factory.createUnionTypeNode([
        ...known.map((value) => factory.createLiteralTypeNode(factory.createStringLiteral(value))),
        anyOtherString,
      ]);
    }
    return undefined;
  },
});

const header = `// Generated by scripts/generate-api.ts from src/api/openapi.yaml. Do not edit.

/** An exact decimal as text, such as "100.00": never a JS number (ADR-0002). */
export type Decimal = \`\${number}\`;

`;

await writeFile(target, header + astToString(ast));
